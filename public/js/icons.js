export const hasIcon = (name) => Object.hasOwn(P, name);

/**
 * @param {string} name  key from the set above
 * @param {{size?:number, stroke?:number, cls?:string, filled?:boolean}} [opts]
 * @returns {string} an `<svg>` string safe to drop into a template
 */
export function icon(name, opts = {}) {
  const body = P[name];
  if (!body) return '';
  const { size = 20, stroke = 2, cls = '', filled = false } = opts;
  return `<svg class="icon ${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" ` +
    `fill="${filled ? 'currentColor' : 'none'}" stroke="${filled ? 'none' : 'currentColor'}" ` +
    `stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round" ` +
    `aria-hidden="true" focusable="false">${body}</svg>`;
}

/**
 * Render a stored icon value. Known names draw from the set; anything else
 * (an emoji someone typed before, say) is passed through as text so no
 * existing category silently loses its symbol.
 */
export function iconOrText(value, opts = {}) {
  if (hasIcon(value)) return icon(value, opts);
  const text = String(value ?? '').trim();
  return text ? `<span class="icon-text">${text.replace(/[&<>"']/g, '')}</span>` : icon('flower', opts);
}
